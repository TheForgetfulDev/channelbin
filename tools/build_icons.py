#!/usr/bin/env python3
"""Write static/icons/mdi-sprite.svg from the icon registry (app/icons.py).

Run from the repo root after `npm ci`, whenever the registry or the pinned `@mdi/js`
version changes:

    python3 tools/build_icons.py

Each registry meaning becomes one `<symbol id="i-<meaning>">` holding its MDI path, copied
out of `node_modules/@mdi/js/mdi.js` - no path is ever typed in by hand.
`tests/test_icon_registry.py` fails when the checked-in sprite differs from what this
writes, so a registry edit without a rebuild cannot ship.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MDI_JS = os.path.join(ROOT, 'node_modules', '@mdi', 'js', 'mdi.js')
OUT = os.path.join(ROOT, 'static', 'icons', 'mdi-sprite.svg')


def camel(mdi_name):
    return 'mdi' + ''.join(p.capitalize() for p in mdi_name.split('-'))


def build(registry, mdi_js_text):
    """The sprite's exact text for `registry` ({meaning: mdi name}) and the package source."""
    m = re.search(r'Material Design Icons v([\d.]+)', mdi_js_text)
    if not m:
        raise ValueError('mdi.js has no "Material Design Icons vX" header line')
    paths = dict(re.findall(r'^export var (mdi\w+) = "([^"]+)";', mdi_js_text, re.M))
    missing = [f'{k} -> {v}' for k, v in registry.items() if camel(v) not in paths]
    if missing:
        raise KeyError(f'not in @mdi/js v{m.group(1)}: {", ".join(missing)}')
    lines = ['<svg xmlns="http://www.w3.org/2000/svg">',
             f'<!-- Generated by tools/build_icons.py from app/icons.py and @mdi/js '
             f'v{m.group(1)}. Do not edit by hand. -->']
    for meaning, mdi_name in registry.items():
        lines.append(f'<symbol id="i-{meaning}" viewBox="0 0 24 24">'
                     f'<path d="{paths[camel(mdi_name)]}"/></symbol>')
    lines.append('</svg>')
    return '\n'.join(lines) + '\n'


def main():
    sys.path.insert(0, ROOT)
    from app.icons import ICONS
    if not os.path.exists(MDI_JS):
        sys.exit(f'{MDI_JS} is missing - run `npm ci` in the repo root first')
    with open(MDI_JS, encoding='utf-8') as fh:
        text = build(ICONS, fh.read())
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(ICONS)} icons, {len(text):,} bytes')


if __name__ == '__main__':
    main()
